export function extractHookBindings(source) {
  const bindings = new Set();
  const body = source.slice(source.indexOf("export function useTripPageModel"));
  for (const line of body.split("\n")) {
    if (!line.startsWith("  ") || line.startsWith("    ")) continue;
    let m = line.match(/^  const \[(\w+), (set\w+)\]/);
    if (m) {
      bindings.add(m[1]);
      bindings.add(m[2]);
      continue;
    }
    m = line.match(/^  const \[(\w+)\]/);
    if (m) {
      bindings.add(m[1]);
      continue;
    }
    m = line.match(/^  const (\w+)\s*=/);
    if (m) {
      bindings.add(m[1]);
      continue;
    }
    m = line.match(/^  let (\w+)\s*=/);
    if (m) {
      bindings.add(m[1]);
      continue;
    }
    m = line.match(/^  (?:async )?function (\w+)/);
    if (m) bindings.add(m[1]);
  }
  return bindings;
}

export function extractReturnKeys(source) {
  const keys = new Set();
  const match = source.match(/return \{([\s\S]*?)\n  \};\n\}/);
  if (!match) return keys;
  for (const line of match[1].split("\n")) {
    const m = line.match(/^\s+(\w+)(?::\s*\w+)?,/);
    if (m) keys.add(m[1]);
  }
  return keys;
}

export function extractStaticApiKeys(source) {
  const keys = new Set();
  for (const block of source.matchAll(/export \{([^}]+)\}/g)) {
    for (const part of block[1].split(",")) {
      const trimmed = part.trim();
      if (!trimmed) continue;
      const alias = trimmed.split(/\s+as\s+/);
      keys.add((alias[1] || alias[0]).trim());
    }
  }
  for (const block of source.matchAll(/export \{ default as (\w+) \}/g)) {
    keys.add(block[1]);
  }
  return keys;
}

export function extractImports(source) {
  const imports = new Set();
  const sharedBlock = source.match(/const\s*\{([^}]+)\}\s*=\s*TripPageShared;/);
  if (sharedBlock) {
    for (const part of sharedBlock[1].split(",")) {
      const name = part.trim().split(":").pop().trim();
      if (name) imports.add(name);
    }
  }
  for (const m of source.matchAll(/^import\s+([\s\S]*?)\s+from\s+['"][^'"]+['"]/gm)) {
    const chunk = m[1].trim();
    if (chunk.startsWith("{")) {
      chunk
        .slice(1, -1)
        .split(",")
        .forEach((s) => {
          const p = s.trim().split(/\s+as\s+/);
          imports.add((p[1] || p[0]).trim());
        });
    } else {
      chunk.split(",").forEach((s) => {
        const p = s.trim().split(/\s+as\s+/);
        imports.add((p[1] || p[0]).trim());
      });
    }
  }
  return imports;
}

export function parseDestructureBlock(source, pattern) {
  const m = source.match(pattern);
  if (!m) return { keys: new Set(), fullMatch: null };
  const keys = new Set();
  for (const part of m[1].split(",")) {
    const name = part.trim().split(":").pop().trim();
    if (name) keys.add(name);
  }
  return { keys, fullMatch: m[0] };
}

/** Collect keys from every `const { ... } = tripPage` / `useTripPage()` in a file. */
export function parseAllDestructureKeys(source, assignee) {
  const keys = new Set();
  const re =
    assignee === "tripPage"
      ? /const\s*\{([^}]+)\}\s*=\s*tripPage;/g
      : /const\s*\{([^}]+)\}\s*=\s*useTripPage\(\);/g;
  for (const m of source.matchAll(re)) {
    for (const part of m[1].split(",")) {
      const name = part.trim().split(":").pop().trim();
      if (name) keys.add(name);
    }
  }
  return keys;
}

export function getConsumerBody(source, filePath) {
  if (filePath === PATHS.tripPage) {
    const fn = source.indexOf("export default function TripPage()");
    return fn === -1 ? source : source.slice(fn);
  }
  const tripPageMatch = source.match(/const\s*\{[\s\S]*?\}\s*=\s*tripPage;/);
  const useTripPageMatch = source.match(/const\s*\{[\s\S]*?\}\s*=\s*useTripPage\(\);/);
  const fullMatch = tripPageMatch?.[0] || useTripPageMatch?.[0] || null;
  const bodyStart = fullMatch ? source.indexOf(fullMatch) + fullMatch.length : 0;
  return source.slice(bodyStart);
}

function isLikelyContextKey(name) {
  if (EXCLUDED_USAGE_NAMES.has(name)) return false;
  return name.length >= 6 || CONTEXT_KEY_RE.test(name);
}

export function findUsedContextKeys(source, availableKeys, imports, filePath = "") {
  const body = getConsumerBody(source, filePath);
  const used = new Set();

  for (const key of availableKeys) {
    if (imports.has(key)) continue;
    if (EXCLUDED_USAGE_NAMES.has(key)) continue;
    if (!isLikelyContextKey(key)) continue;
    const re = new RegExp(`\\b${key}\\b`);
    if (!re.test(body)) continue;
    // Skip bare object keys (`key:`) but allow `key &&`, `key.`, `key(`, etc.
    if (new RegExp(`\\b${key}\\s*:`).test(body) && !new RegExp(`\\b${key}\\s*(&&|\\|\\||\\?|\\.|;|,|\\)|$)`).test(body)) {
      continue;
    }
    used.add(key);
  }
  return used;
}

export function formatDestructure(keys) {
  const sorted = [...keys].sort();
  const lines = sorted.map((k) => `    ${k},`);
  return `const {\n${lines.join("\n")}\n  }`;
}

export function replaceDestructure(source, pattern, replacement) {
  return source.replace(pattern, replacement);
}

export function getAllAvailableKeys(hookSource, staticSource) {
  const hookReturn = extractReturnKeys(hookSource);
  const staticKeys = extractStaticApiKeys(staticSource);
  const hookBindings = extractHookBindings(hookSource);
  return {
    hookReturn,
    staticKeys,
    hookBindings,
    available: new Set([...hookReturn, ...staticKeys]),
  };
}

/** Bindings that should stay private to the hook (loaders, effects helpers). */
const PRIVATE_BINDING_PREFIXES = ["load", "onVisibility", "handleTaskUpdate", "syncStaff"];

export function isPrivateBinding(name) {
  if (name.startsWith("_")) return true;
  return PRIVATE_BINDING_PREFIXES.some((p) => name.startsWith(p) || name === p);
}

